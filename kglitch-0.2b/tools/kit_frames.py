"""The player's drum samples (LOAF BREAKER 0.9.45, FLEXOR: the site's IMPORT page) as the page makes them: a snare,
a hat and a clap from any WAVs, each trimmed (the silence before it, the tail once quiet), at most a second, its peak
at -0.3 dBFS, faded out, at the highest rate that lets the three fit (22050, then 16000, then 11025 Hz: the kit is
8 KB of flash, app.c KIT_AT), IMA ADPCM as the breaks; then the SysEx frames that write it (zone 2, ui/main.c
kit_sysex). For the tests:
    python3 tools/kit_frames.py SN=FILE.wav:NAME HH=FILE.wav:NAME CP=FILE.wav:NAME > build/kit.txt   a host scenario
    python3 tools/kit_frames.py --kit SN=... OUT.bin                                                  the image"""
import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import prep_breaks as pb  # noqa: E402
import cu_frames as cf  # noqa: E402

KIT_CAP = 8192                                      # app.c KIT_CAP: the two sectors of 0xDE000
KIT_MAGIC = 0x314B5244                              # "DRK1"
HEAD = 16 + 3 * 24
RATES = (22050, 16000, 11025)
VOICES = ("SN", "HH", "CP")
MAX_S = 1.0                                         # a sample at most a second


def trim(x, rate):
    """the silence before it (-50 dBFS, 1 ms kept), its tail once under -60 dBFS for good, a second at most"""
    pk = max((abs(v) for v in x), default=0.0)
    if pk <= 0.0:
        return []
    a = next(i for i, v in enumerate(x) if abs(v) >= pk * 0.00316)
    a = max(0, a - rate // 1000)
    b = len(x)
    while b > a and abs(x[b - 1]) < pk * 0.001:
        b -= 1
    return x[a:min(b, a + int(MAX_S * rate))]


def shape(x, rate):
    """its peak at -0.3 dBFS, the last 4 ms faded out"""
    pk = max((abs(v) for v in x), default=0.0)
    g = 0.966 / pk if pk > 0 else 0.0
    y = [v * g for v in x]
    f = min(len(y), max(1, rate * 4 // 1000))
    for i in range(f):
        y[len(y) - f + i] *= 1.0 - (i + 1) / f
    return y


def kit(specs):
    """specs: {voice index: (wav, name)}; the image (header, three entries, the data) and the rate it took"""
    src = {}
    for v, (w, name) in specs.items():
        x, r = pb.read_wav(w)
        src[v] = (trim(x, r), r, name)
    for rate in RATES:
        lens = {v: int(len(x) * rate / r) for v, (x, r, _) in src.items()}
        if HEAD + sum((n + 1) // 2 for n in lens.values()) <= KIT_CAP:
            break
    else:                                           # still too long at 11025: each cut in proportion
        rate = RATES[-1]
        room = (KIT_CAP - HEAD) * 2 - 2 * len(src)
        tot = sum(int(len(x) * rate / r) for x, r, _ in src.values())
        src = {v: (x[:int(len(x) * room / tot)], r, n) for v, (x, r, n) in src.items()}
    ents, data = [], bytearray()
    for v in range(3):
        if v not in src or not src[v][0]:
            ents.append(struct.pack("<III12s", 0, 0, 0, b""))
            continue
        x, r, name = src[v]
        y = shape(pb.resample(x, r, rate), rate)
        a = pb.adpcm_encode(y)
        ents.append(struct.pack("<III12s", HEAD + len(data), len(y), rate, name.upper().encode()[:12]))
        data += a
    body = b"".join(ents) + bytes(data)
    return struct.pack("<IIII", KIT_MAGIC, zlib.crc32(body), len(body), 0) + body, rate


def frames(img):
    u32 = lambda v: v.to_bytes(4, "little")  # noqa: E731
    yield "begin", cf.frame(0x22, u32(len(img)))
    for off in range(16, len(img), cf.CHUNK):
        yield "data", cf.frame(0x23, u32(off) + img[off:off + cf.CHUNK])
    yield "commit", cf.frame(0x24, img[:16])


def parse(args):
    specs = {}
    for a in args:
        v, rest = a.split("=", 1)
        w, name = rest.rsplit(":", 1)
        specs[VOICES.index(v)] = (w, name)
    return specs


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["--kit"]:
        img, _ = kit(parse(a[1:-1]))
        Path(a[-1]).write_bytes(img)
        raise SystemExit
    img, rate = kit(parse(a))
    print(f"# generated by tools/kit_frames.py: {len(img)} B at {rate} Hz")
    for kind, f in frames(img):
        print(f"sysex {cf.hexs(f)}")
        print("wait 20" if kind == "data" else "wait 200")
