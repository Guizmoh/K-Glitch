# The player's drum samples (LOAF BREAKER 0.9.45, FLEXOR: the site's IMPORT page) end to end in the host simulator: a
# snare, a hat and a clap made into a kit as the page makes it (tools/kit_frames.py), uploaded over SysEx (zone 2);
# refused while playing; INFO; the snare's PRESET past its last built-in is its sample, heard on key 2; kept through a
# reboot; deleted: the synthesis again. Needs ./build.sh --host first.
#   tests/drum_kit.sh
set -e
cd "$(dirname "$0")/.."
O=app/build/kit
mkdir -p "$O"
python3 - "$O" <<'P'
import math, random, struct, sys, wave
o = sys.argv[1]
def w(name, sec, f):
    n = int(44100 * sec)
    x = [f(i / 44100.0) for i in range(n)]
    with wave.open(f"{o}/{name}.wav", "wb") as h:
        h.setnchannels(1); h.setsampwidth(2); h.setframerate(44100)
        h.writeframes(b"".join(struct.pack("<h", int(max(-1, min(1, v)) * 30000)) for v in x))
random.seed(3)
w("sn", 0.35, lambda t: (0.03 if t < 0.02 else 0) * 0 + (math.sin(2 * math.pi * 190 * t) * 0.6 + random.uniform(-1, 1) * 0.5) * math.exp(-t / 0.07) if t > 0.01 else 0.0)
w("hh", 0.12, lambda t: random.uniform(-1, 1) * math.exp(-t / 0.02))
w("cp", 0.3, lambda t: random.uniform(-1, 1) * math.exp(-t / 0.06))
P
H="$(ls app/build/host/*_host | head -1)"
INFO0=$(python3 -c "
import sys; sys.path.insert(0,'tools'); import cu_frames as c
print(c.hexs(bytes([0xF0,0x7D,0x43,0x48,0x61,0]) + c.pack7((8192).to_bytes(4,'little') + bytes(4 + 60)) + bytes([0xF7])))")
{
cat <<S
# (generated by tests/drum_kit.sh)
wait 4200
expect kit 0
sysex_out
sysex F0 7D 43 48 21 F7
wait 50
expect_sysex $INFO0
tap PLAY
wait 300
sysex F0 7D 43 48 22 00 00 10 00 00 F7
wait 100
expect_sysex F0 7D 43 48 62 01 F7
tap PLAY
wait 300
S
python3 tools/kit_frames.py SN=$O/sn.wav:MYSNARE HH=$O/hh.wav:MYHAT CP=$O/cp.wav:MYCLAP | tail -n +2
cat <<'S'
expect_sysex F0 7D 43 48 64 00 F7
expect kit 7
press SEL
tap EDIT
release SEL
wait 400
expect page 7
expect ppre 0
turn ALGO 1 60
wait 200
turn K3 -1 60
wait 300
expect ppre 13
expect psmp 1
wait 1500
shot kit_snare.png
peakreset
tapkey w1
wait 600
expect peak_db_min -30
tap SAVE
wait 800
reboot
wait 4200
expect kit 7
expect psmp 1
sysex F0 7D 43 48 26 F7
wait 300
expect_sysex F0 7D 43 48 66 00 F7
expect kit 0
expect psmp 0
S
} > "$O/kit.txt"
"$H" "$O/kit.txt" "$O"
echo "drum_kit: three samples uploaded, the snare's PRESET its sample and heard, kept through a reboot, deleted"
